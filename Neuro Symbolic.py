# CELL 10 — Cross-Validation Experiment Runner
# 5-fold × 10 repeat = 50 runs, paired t-tests
# ============================================================

class CrossValidationExperiment:
    """
    Runs rigorous cross-validation to address statistical validity concerns.
    """

    def __init__(self, n_folds=5, n_repeats=3, n_clusters=3, latent_dim=8,
                 n_epochs=30):
        # Reduced repeats for notebook speed — set n_repeats=10 for paper
        self.n_folds = n_folds
        self.n_repeats = n_repeats
        self.n_clusters = n_clusters
        self.latent_dim = latent_dim
        self.n_epochs = n_epochs

    def run(self, X, dataset_name="Dataset"):
        """
        Runs cross-validation for NeSy framework and baselines.
        Returns results dict with per-fold scores.
        """
        print(f"\n{'='*60}")
        print(f"Cross-Validation: {dataset_name}")
        print(f"  Folds: {self.n_folds}, Repeats: {self.n_repeats}")
        print(f"  Total runs: {self.n_folds * self.n_repeats}")
        print(f"{'='*60}")

        results = {
            'NeSy_Framework': [],
            'Type1_Fuzzy': [],
            'DBSCAN': [],
            'Agglomerative': []
        }

        n = len(X)
        for rep in range(self.n_repeats):
            kf = KFold(n_splits=self.n_folds, shuffle=True,
                       random_state=42 + rep)
            for fold, (train_idx, test_idx) in enumerate(kf.split(X)):
                X_train = X[train_idx]
                X_test = X[test_idx]

                # ---- NeSy Framework ----
                try:
                    framework = ConstraintAwareNeSyFramework(
                        input_dim=X_train.shape[1],
                        latent_dim=self.latent_dim,
                        n_clusters=self.n_clusters,
                        n_epochs=self.n_epochs
                    )
                    framework.fit(X_train, verbose=False)
                    Z_test = framework.get_latent(X_test)
                    _, U_lower, U_upper = framework.fuzzy_module.fit(Z_test)
                    U_avg = (U_lower + U_upper) / 2.0
                    labels_nesy = np.argmax(U_avg, axis=0)
                    metrics = evaluate_clustering(Z_test, labels_nesy)
                    results['NeSy_Framework'].append(metrics['silhouette'])
                except Exception as e:
                    print(f"  NeSy error fold {fold}: {e}")
                    results['NeSy_Framework'].append(np.nan)

                # ---- Baselines on PCA-preprocessed test data ----
                baseline = run_baselines(X_test, n_clusters=self.n_clusters)
                for method in ['Type1_Fuzzy', 'DBSCAN', 'Agglomerative']:
                    sil = baseline.get(method, {}).get('silhouette', np.nan)
                    results[method].append(sil)

                print(f"  Rep {rep+1}, Fold {fold+1} done.", end='\r')

        print("\n")
        return results

    def statistical_analysis(self, results, dataset_name=""):
        """
        Paired t-tests between NeSy and each baseline.
        Addresses reviewer concern about statistical rigor.
        """
        print(f"\n--- Statistical Analysis: {dataset_name} ---")
        nesy_scores = np.array(results['NeSy_Framework'])
        nesy_clean = nesy_scores[~np.isnan(nesy_scores)]

        stats_out = {}
        for method in ['Type1_Fuzzy', 'DBSCAN', 'Agglomerative']:
            other_scores = np.array(results[method])
            other_clean = other_scores[~np.isnan(other_scores)]
            # Match lengths
            min_len = min(len(nesy_clean), len(other_clean))
            if min_len < 2:
                stats_out[method] = {'t': np.nan, 'p': np.nan}
                continue
            t_stat, p_val = stats.ttest_rel(
                nesy_clean[:min_len], other_clean[:min_len]
            )
            sig = "***" if p_val < 0.001 else ("**" if p_val < 0.01
                                                 else ("*" if p_val < 0.05 else "ns"))
            mean_nesy = np.mean(nesy_clean)
            ci = stats.t.interval(0.95, len(nesy_clean)-1,
                                  loc=mean_nesy,
                                  scale=stats.sem(nesy_clean))
            stats_out[method] = {
                't': round(t_stat, 4), 'p': round(p_val, 5),
                'sig': sig, 'nesy_mean': round(mean_nesy, 4),
                'nesy_ci': (round(ci[0], 4), round(ci[1], 4)),
                'other_mean': round(np.mean(other_clean), 4)
            }
            print(f"  NeSy vs {method:<16}: "
                  f"t={t_stat:.3f}, p={p_val:.4f} {sig} | "
                  f"NeSy={mean_nesy:.4f}±[{ci[0]:.4f},{ci[1]:.4f}] "
                  f"vs {method}={np.mean(other_clean):.4f}")
        return stats_out


print("Cross-validation experiment runner defined.")


