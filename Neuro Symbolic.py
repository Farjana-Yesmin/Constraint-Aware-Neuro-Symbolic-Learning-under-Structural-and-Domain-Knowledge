def run_ablation(X, dataset_name="", n_epochs=30, latent_dim=8):
    """
    Ablation: compare full NeSy vs. variants without each component.
    Variants:
    1. Full NeSy (neural + symbolic constraints + bidirectional)
    2. No neural: just Type-2 Fuzzy on PCA features (symbolic only)
    3. No symbolic constraint loss: neural encoder + clustering, no constraint penalty
    4. No bidirectional: only symbolic→neural (no rule extraction feedback)
    """
    print(f"\n--- Ablation Study: {dataset_name} ---")
    n = len(X)

    ablation_results = {}

    # Variant 1: Full NeSy
    fw = ConstraintAwareNeSyFramework(
        input_dim=X.shape[1], latent_dim=latent_dim,
        n_clusters=3, lambda_cluster=1.0, lambda_constraint=0.5,
        n_epochs=n_epochs
    )
    fw.fit(X, verbose=False)
    Z = fw.Z_latent
    labels = fw.get_cluster_labels()
    ablation_results['Full NeSy'] = evaluate_clustering(Z, labels)

    # Variant 2: No neural (Type-2 Fuzzy on raw PCA features only)
    fz = Type2FuzzyConstraintModule(n_clusters=3)
    fz.fit(X)
    labels_no_neural = np.argmax(fz.get_avg_memberships(), axis=0)
    ablation_results['No Neural (Symbolic Only)'] = evaluate_clustering(X, labels_no_neural)

    # Variant 3: No symbolic constraint loss (λ_constraint = 0)
    fw_no_sym = ConstraintAwareNeSyFramework(
        input_dim=X.shape[1], latent_dim=latent_dim,
        n_clusters=3, lambda_cluster=1.0, lambda_constraint=0.0,
        n_epochs=n_epochs
    )
    fw_no_sym.fit(X, verbose=False)
    Z_no_sym = fw_no_sym.Z_latent
    labels_no_sym = fw_no_sym.get_cluster_labels()
    ablation_results['No Symbolic Constraints'] = evaluate_clustering(Z_no_sym, labels_no_sym)

    # Variant 4: No clustering loss (λ_cluster = 0)
    fw_no_cluster = ConstraintAwareNeSyFramework(
        input_dim=X.shape[1], latent_dim=latent_dim,
        n_clusters=3, lambda_cluster=0.0, lambda_constraint=0.5,
        n_epochs=n_epochs
    )
    fw_no_cluster.fit(X, verbose=False)
    Z_no_cl = fw_no_cluster.Z_latent
    labels_no_cl = fw_no_cluster.get_cluster_labels()
    ablation_results['No Clustering Loss'] = evaluate_clustering(Z_no_cl, labels_no_cl)

    print(f"{'Variant':<30} {'Silhouette':<12} {'CH Score':<12} {'DB Score':<12}")
    print("-" * 66)
    for variant, metrics in ablation_results.items():
        sil = metrics.get('silhouette', np.nan)
        ch = metrics.get('calinski_harabasz', np.nan)
        db = metrics.get('davies_bouldin', np.nan)
        print(f"{variant:<30} {sil:<12.4f} {ch:<12.2f} {db:<12.4f}")

    return ablation_results


print("Ablation study defined.")


