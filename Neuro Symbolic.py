# CELL 9 — Evaluation Framework
# Key fix: evaluation uses EXTERNAL metrics (not derived from
# fuzzy memberships themselves) to avoid self-referential scoring.
# ============================================================

def evaluate_clustering(X, labels, method_name=""):
    """
    External clustering quality metrics — NOT derived from fuzzy memberships.
    This directly addresses Reviewer #3's self-referential evaluation concern.
    """
    if len(np.unique(labels)) < 2:
        return {m: np.nan for m in
                ['silhouette', 'calinski_harabasz', 'davies_bouldin']}
    sil = silhouette_score(X, labels, sample_size=min(5000, len(X)))
    ch = calinski_harabasz_score(X, labels)
    db = davies_bouldin_score(X, labels)
    return {
        'silhouette': round(sil, 4),
        'calinski_harabasz': round(ch, 2),
        'davies_bouldin': round(db, 4)
    }


def run_baselines(X, n_clusters=3):
    """Run baseline methods for comparison"""
    results = {}

    # Type-1 Fuzzy (standard FCM without neural component)
    try:
        cntr, u, _, _, _, _, _ = fuzz.cluster.cmeans(
            X.T, n_clusters, 2, error=0.005, maxiter=1000
        )
        labels_t1 = np.argmax(u.T, axis=1)
        results['Type1_Fuzzy'] = evaluate_clustering(X, labels_t1)
        results['Type1_Fuzzy']['labels'] = labels_t1
    except Exception as e:
        results['Type1_Fuzzy'] = {'silhouette': np.nan, 'error': str(e)}

    # DBSCAN
    try:
        db = DBSCAN(eps=0.5, min_samples=5, n_jobs=-1).fit(X)
        if len(np.unique(db.labels_)) > 1:
            results['DBSCAN'] = evaluate_clustering(X, db.labels_)
            results['DBSCAN']['labels'] = db.labels_
        else:
            results['DBSCAN'] = {'silhouette': np.nan, 'note': 'single cluster'}
    except Exception as e:
        results['DBSCAN'] = {'silhouette': np.nan, 'error': str(e)}

    # Agglomerative (limited to 10k samples for memory)
    try:
        n_sub = min(10000, len(X))
        ag = AgglomerativeClustering(n_clusters=n_clusters).fit(X[:n_sub])
        results['Agglomerative'] = evaluate_clustering(X[:n_sub], ag.labels_)
        results['Agglomerative']['labels'] = ag.labels_
    except Exception as e:
        results['Agglomerative'] = {'silhouette': np.nan, 'error': str(e)}

    return results


