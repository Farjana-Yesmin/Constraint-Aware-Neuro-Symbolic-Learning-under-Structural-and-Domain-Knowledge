def run_full_experiment():
    """
    Main experimental pipeline across 5 datasets, 4 domains.
    Generates all tables and figures needed for the NeSy paper.
    """
    datasets_to_load = [
        load_air_quality,
        load_covertype,
        load_electricity,
        load_credit_fraud,
        load_kddcup99
    ]

    all_results = {}
