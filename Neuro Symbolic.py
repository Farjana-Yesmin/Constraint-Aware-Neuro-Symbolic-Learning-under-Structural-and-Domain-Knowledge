def compute_domain_knowledge_bounds_aq(X_scaled_input,
                                        co_idx=0, nox_idx=1,
                                        n_clusters=3):
    """WHO-derived bounds for Air Quality dataset."""
    n = X_scaled_input.shape[0]
    u_lower = np.ones((n_clusters, n)) * 0.05
    u_upper = np.ones((n_clusters, n)) * 0.95

    co = X_scaled_input[:, co_idx] if X_scaled_input.shape[1] > co_idx else \
         np.zeros(n)
    nox = X_scaled_input[:, nox_idx] if X_scaled_input.shape[1] > nox_idx else \
          np.zeros(n)

    clean = (co < WHO_BOUNDS['CO_low']) & (nox < WHO_BOUNDS['NOx_low'])
    polluted = (co > WHO_BOUNDS['CO_high']) | (nox > WHO_BOUNDS['NOx_high'])
    intermediate = ~clean & ~polluted

    # Clean: high membership to cluster 0, low to cluster 2
    u_lower[0, clean] = 0.60; u_upper[0, clean] = 0.95
    u_lower[2, clean] = 0.01; u_upper[2, clean] = 0.20

    # Polluted: high membership to cluster 2, low to cluster 0
    u_lower[2, polluted] = 0.60; u_upper[2, polluted] = 0.95
    u_lower[0, polluted] = 0.01; u_upper[0, polluted] = 0.20

    # Intermediate: wide bounds
    u_lower[:, intermediate] = 0.10
    u_upper[:, intermediate] = 0.90

    print(f"  WHO classification — Clean: {clean.sum()} "
          f"({clean.mean()*100:.1f}%), "
          f"Polluted: {polluted.sum()} ({polluted.mean()*100:.1f}%), "
          f"Intermediate: {intermediate.sum()} ({intermediate.mean()*100:.1f}%)")
    return u_lower, u_upper


# ----------------------------------------------------------------
# BLOCK 2: DK-constrained FCM (self-contained)
# ----------------------------------------------------------------

def dk_constrained_fcm(X_cluster, X_orig_for_bounds,
                        bounds_fn, n_clusters=3, m=2,
                        error=0.005, maxiter=1000, **bound_kwargs):
    """
    Type-2 FCM constrained by external domain knowledge bounds.
    bounds_fn: function(X_orig, n_clusters, **kwargs) -> (u_lower, u_upper)
    """
    n = X_cluster.shape[0]
    dk_lower, dk_upper = bounds_fn(X_orig_for_bounds,
                                    n_clusters=n_clusters,
                                    **bound_kwargs)

    # Init memberships within domain bounds
    u = np.random.dirichlet(np.ones(n_clusters), size=n).T
    u = np.clip(u, dk_lower, dk_upper)
    u = u / (u.sum(axis=0, keepdims=True) + 1e-10)

    obj_history = []
    for iteration in range(maxiter):
        u_m = u ** m
        centers = (u_m @ X_cluster) / (u_m.sum(axis=1, keepdims=True) + 1e-10)

        dist = np.array([
            np.linalg.norm(X_cluster - centers[i], axis=1)
            for i in range(n_clusters)
        ])
        dist = np.maximum(dist, 1e-10)

        power = 2.0 / (m - 1)
        u_new = dist ** (-power)
        u_new = u_new / (u_new.sum(axis=0, keepdims=True) + 1e-10)

        # Clip to domain bounds (symbolic injection step)
        u_new = np.clip(u_new, dk_lower, dk_upper)
        u_new = u_new / (u_new.sum(axis=0, keepdims=True) + 1e-10)

        J = float(((u_new ** m) * (dist ** 2)).sum())
        obj_history.append(J)

        if np.max(np.abs(u_new - u)) < error:
            print(f"  DK-FCM converged at iteration {iteration+1}, J={J:.4f}")
            break
        u = u_new

    labels = np.argmax(u, axis=0)
    u_lower_final = np.maximum(u - 0.05, dk_lower)
    u_upper_final = np.minimum(u + 0.05, dk_upper)
    return centers, u, u_lower_final, u_upper_final, labels, obj_history


# ----------------------------------------------------------------
# BLOCK 3: Soft and Hard Constraint Satisfaction
# Addresses reviewer: "CS metric is overly strict"
# ----------------------------------------------------------------

def compute_cs_metrics(u_final, dk_lower, dk_upper):
    """
    Hard CS: fraction of points where ALL cluster bounds are satisfied.
    Soft CS: fraction of (point, cluster) pairs in bounds — less strict.
    """
    within = (u_final >= dk_lower - 1e-6) & (u_final <= dk_upper + 1e-6)
    hard_cs = float(within.all(axis=0).mean())
    soft_cs = float(within.mean())
    per_cluster = within.mean(axis=1)
    return hard_cs, soft_cs, per_cluster


# ----------------------------------------------------------------
# BLOCK 4: Standard Type-2 FCM (self-contained)
# ----------------------------------------------------------------

def run_standard_t2(X, n_clusters=3, m=2):
    cntr, u, _, _, _, _, _ = fuzz.cluster.cmeans(
        X.T, n_clusters, m, error=0.005, maxiter=1000, init=None
    )
    u_lower = np.maximum(u - 0.1 * u, 0)
    u_upper = np.minimum(u + 0.1 * u, 1)
    return cntr, u, u_lower, u_upper


