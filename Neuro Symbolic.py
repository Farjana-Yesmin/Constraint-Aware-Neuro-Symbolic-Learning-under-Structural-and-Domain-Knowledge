# CELL 7 — Constraint-Aware NeSy Framework
# Combines neural + symbolic in a unified training loop.
# ============================================================

class ConstraintAwareNeSyFramework:
    """
    Constraint-Aware Neuro-Symbolic Framework.

    Architecture:
      Input X
        → Neural Encoder   (sub-symbolic learning)
        ↓ Latent Z
        → Type-2 Fuzzy Layer  (symbolic constraints)
        ↓ [U_lower, U_upper]
        → Linguistic Rules  (symbolic output)
        → Neural Decoder   (reconstruction, trains encoder)

    Bidirectional integration: -
      Symbolic → Neural: constraint violation loss backprops through encoder
      Neural → Symbolic: encoder latent Z updates cluster centers & rules
    """

    def __init__(self, input_dim, latent_dim=8, n_clusters=3,
                 lambda_cluster=1.0, lambda_constraint=0.5,
                 lr=1e-3, n_epochs=50):
        self.input_dim = input_dim
        self.latent_dim = latent_dim
        self.n_clusters = n_clusters
        self.lambda_cluster = lambda_cluster   # weight for clustering loss
        self.lambda_constraint = lambda_constraint  # weight for constraint loss
        self.lr = lr
        self.n_epochs = n_epochs

        # Neural components
        self.encoder = NeuralEncoder(input_dim, latent_dim).to(device)
        self.decoder = NeuralDecoder(latent_dim, input_dim).to(device)

        # Symbolic component
        self.fuzzy_module = Type2FuzzyConstraintModule(n_clusters=n_clusters)

        # Cluster centers as learnable parameters (jointly optimized)
        self.centers = nn.Parameter(
            torch.randn(n_clusters, latent_dim, device=device) * 0.1
        )

        # Optimizer covers both neural params and cluster centers
        self.optimizer = optim.Adam(
            list(self.encoder.parameters()) +
            list(self.decoder.parameters()) +
            [self.centers],
            lr=lr, weight_decay=1e-4
        )
        self.scheduler = optim.lr_scheduler.StepLR(
            self.optimizer, step_size=20, gamma=0.5
        )

        self.history = {
            'reconstruction': [], 'clustering': [],
            'constraint': [], 'total': []
        }

    def fit(self, X_np, verbose=True):
        """
        Joint training of neural encoder + symbolic constraints.
        X_np: (n, input_dim) numpy array
        """
        X_tensor = torch.FloatTensor(X_np).to(device)
        dataset = TensorDataset(X_tensor)
        loader = DataLoader(dataset, batch_size=256, shuffle=True)
        n = len(X_np)

        # Phase 1: Warm-up — run fuzzy on raw PCA features to init centers
        print("Phase 1: Initializing symbolic constraints from data...")
        self.fuzzy_module.fit(X_np[:min(5000, n)])
        init_centers = torch.FloatTensor(self.fuzzy_module.centers).to(device)
        # Map raw centers to latent dim via random linear projection (init)
        with torch.no_grad():
            # Encode a subset to initialize cluster centers in latent space
            sample = torch.FloatTensor(X_np[:min(2000, n)]).to(device)
            Z_init = self.encoder(sample).detach().cpu().numpy()
            self.fuzzy_module.fit(Z_init)
            init_centers_latent = torch.FloatTensor(self.fuzzy_module.centers).to(device)
            self.centers.data = init_centers_latent

        # Phase 2: Joint neuro-symbolic training
        print("Phase 2: Joint neuro-symbolic training...")
        self.encoder.train()
        self.decoder.train()

        for epoch in range(self.n_epochs):
            epoch_losses = {'recon': 0, 'cluster': 0, 'constraint': 0, 'total': 0}

            for (batch_x,) in loader:
                self.optimizer.zero_grad()

                # Neural forward pass
                Z = self.encoder(batch_x)       # latent representation
                X_hat = self.decoder(Z)         # reconstruction

                # Loss 1: Reconstruction (neural)
                L_recon = nn.MSELoss()(X_hat, batch_x)

                # Loss 2: Clustering in latent space (symbolic objective)
                L_cluster, U_batch = compute_fuzzy_clustering_loss(
                    Z, self.centers, m=2.0
                )

                # Loss 3: Symbolic constraint violation (symbolic→neural)
                # Use current fuzzy module bounds on this batch
                Z_np = Z.detach().cpu().numpy()
                _, U_lower_np, U_upper_np = self.fuzzy_module.fit(Z_np)
                U_lower_t = torch.FloatTensor(U_lower_np).to(device)
                U_upper_t = torch.FloatTensor(U_upper_np).to(device)
                L_constraint = compute_constraint_violation_loss(
                    U_batch, U_lower_t, U_upper_t
                )

                # Total loss with symbolic constraints guiding neural learning
                L_total = (L_recon +
                           self.lambda_cluster * L_cluster +
                           self.lambda_constraint * L_constraint)

                L_total.backward()
                nn.utils.clip_grad_norm_(
                    list(self.encoder.parameters()) +
                    list(self.decoder.parameters()), max_norm=1.0
                )
                self.optimizer.step()

                epoch_losses['recon'] += L_recon.item()
                epoch_losses['cluster'] += L_cluster.item()
                epoch_losses['constraint'] += L_constraint.item()
                epoch_losses['total'] += L_total.item()

            n_batches = len(loader)
            self.history['reconstruction'].append(epoch_losses['recon'] / n_batches)
            self.history['clustering'].append(epoch_losses['cluster'] / n_batches)
            self.history['constraint'].append(epoch_losses['constraint'] / n_batches)
            self.history['total'].append(epoch_losses['total'] / n_batches)
            self.scheduler.step()

            if verbose and (epoch + 1) % 10 == 0:
                print(f"  Epoch {epoch+1:3d}/{self.n_epochs} | "
                      f"Recon: {epoch_losses['recon']/n_batches:.4f} | "
                      f"Cluster: {epoch_losses['cluster']/n_batches:.4f} | "
                      f"Constraint: {epoch_losses['constraint']/n_batches:.4f}")

        # Phase 3: Final symbolic fit on full learned latent space
        print("Phase 3: Final symbolic fitting on full latent space...")
        self.encoder.eval()
        with torch.no_grad():
            X_t = torch.FloatTensor(X_np).to(device)
            Z_full = self.encoder(X_t).cpu().numpy()
        self.fuzzy_module.fit(Z_full)
        self.Z_latent = Z_full
        print("Training complete.")
        return self

    def get_cluster_labels(self):
        """Returns hard cluster assignments from learned representation"""
        U_avg = self.fuzzy_module.get_avg_memberships()  # (c, n)
        return np.argmax(U_avg, axis=0)  # (n,)

    def get_latent(self, X_np):
        """Encodes new data (neural → symbolic direction)"""
        self.encoder.eval()
        with torch.no_grad():
            X_t = torch.FloatTensor(X_np).to(device)
            Z = self.encoder(X_t).cpu().numpy()
        return Z

    def plot_training_history(self, title=""):
        fig, axes = plt.subplots(1, 2, figsize=(12, 4))
        axes[0].plot(self.history['reconstruction'], label='Reconstruction', color='blue')
        axes[0].plot(self.history['clustering'], label='Clustering', color='orange')
        axes[0].plot(self.history['constraint'], label='Constraint', color='red')
        axes[0].set_xlabel('Epoch')
        axes[0].set_ylabel('Loss')
        axes[0].set_title(f'Training Losses {title}')
        axes[0].legend()
        axes[0].grid(True, alpha=0.3)

        axes[1].plot(self.history['total'], label='Total Loss', color='black', linewidth=2)
        axes[1].set_xlabel('Epoch')
        axes[1].set_ylabel('Total Loss')
        axes[1].set_title(f'Total Loss {title}')
        axes[1].legend()
