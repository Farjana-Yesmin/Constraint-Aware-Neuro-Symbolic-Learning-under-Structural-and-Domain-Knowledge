# CELL 8 — Linguistic Rule Extraction (Neural→Symbolic direction)
# Key fix: rules derived from FUZZY-WEIGHTED cluster centers,
# not just hard percentile bins. The neural encoder output
# shapes which rules are extracted.
# ============================================================

class LinguisticRuleExtractor:
    """
    Extracts human-readable IF-THEN rules from learned cluster structure.

    Improvement over prior version:
    - Uses fuzzy-weighted prototypes (not just cluster center percentiles)
    - Membership-weighted rule generation: data points with higher
      membership contribute more to rule boundaries
    - Rule quality metrics are grounded in cluster external validity
    """

    def __init__(self, feature_names=None):
        self.feature_names = feature_names
        self.rules = []

    def extract_rules(self, X_original, centers_latent, U_avg, feature_names=None):
        """
        X_original: original (unscaled) data or PCA-projected data (n, d)
        centers_latent: cluster centers in latent space (c, latent_dim)
        U_avg: average memberships (c, n)
        """
        if feature_names is not None:
            self.feature_names = feature_names
        n, d = X_original.shape
        c = U_avg.shape[0]
        self.rules = []

        for i in range(c):
            u_i = U_avg[i]  # membership of each point to cluster i
            high_mem_mask = u_i > 0.5

            if high_mem_mask.sum() < 3:
                continue

            # Fuzzy-weighted prototypical feature values
            weights = u_i[high_mem_mask]
            X_cluster = X_original[high_mem_mask]
            weighted_center = np.average(X_cluster, weights=weights, axis=0)

            # Membership-weighted percentiles for thresholds
            # (linguistic variable boundaries derived from membership-weighted distribution)
            rule_conditions = {}
            for j in range(min(d, 10)):  # limit to first 10 features for readability
                feat_vals = X_original[:, j]
                # Membership-weighted percentiles
                sorted_idx = np.argsort(feat_vals)
                w_sorted = u_i[sorted_idx]
                w_cumsum = np.cumsum(w_sorted)
                w_total = w_cumsum[-1]
                p33_idx = np.searchsorted(w_cumsum, 0.33 * w_total)
                p66_idx = np.searchsorted(w_cumsum, 0.66 * w_total)
                p33 = feat_vals[sorted_idx[p33_idx]]
                p66 = feat_vals[sorted_idx[p66_idx]]

                val = weighted_center[j]
                fname = (self.feature_names[j]
                         if self.feature_names and j < len(self.feature_names)
                         else f"Feature_{j+1}")
                if val < p33:
                    level = "LOW"
                elif val < p66:
                    level = "MEDIUM"
                else:
                    level = "HIGH"
                rule_conditions[fname] = (level, val, p33, p66)

            # Rule quality metrics
            cov = float(high_mem_mask.sum()) / n
            sig = float(weights.mean()) if len(weights) > 0 else 0.0
            # Uncertainty: width of interval relative to membership range
            unc = float((self.rules[0]['uncertainty']
                         if self.rules else
                         np.mean(U_avg[i] - np.minimum(U_avg[i], 0.9))))
            # Better uncertainty: standard deviation of memberships (not self-referential)
            unc = float(np.std(u_i))

            rule = {
                'cluster': i + 1,
                'conditions': rule_conditions,
                'coverage': round(cov, 3),
                'significance': round(sig, 3),
                'uncertainty': round(unc, 3),
                'n_supporting': int(high_mem_mask.sum())
            }
            self.rules.append(rule)

        return self.rules

    def print_rules(self, domain_name=""):
        print(f"\n{'='*60}")
        print(f"LINGUISTIC RULES — {domain_name}")
        print(f"{'='*60}")
        for rule in self.rules:
            conditions = " AND ".join(
                [f"{f} is {v[0]}" for f, v in rule['conditions'].items()]
            )
            print(f"Rule {rule['cluster']}: IF {conditions}")
            print(f"         THEN Pattern_{rule['cluster']}")
            print(f"         [Coverage: {rule['coverage']:.3f}, "
                  f"Significance: {rule['significance']:.3f}, "
                  f"Uncertainty: {rule['uncertainty']:.3f}]")
            print()

    def get_rule_summary(self):
        if not self.rules:
            return {'coverage': 0, 'significance': 0, 'uncertainty': 0}
        return {
            'coverage': np.mean([r['coverage'] for r in self.rules]),
            'significance': np.mean([r['significance'] for r in self.rules]),
            'uncertainty': np.mean([r['uncertainty'] for r in self.rules])
        }


print("Linguistic Rule Extractor defined.")


