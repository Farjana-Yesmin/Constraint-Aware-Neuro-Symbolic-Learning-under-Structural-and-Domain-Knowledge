# CELL 5 — Type-2 Fuzzy Constraint Module (Symbolic Component)
# This is the SYMBOLIC component. It imposes interval-valued
# fuzzy membership constraints on the neural latent space.
# Key fix vs. old code: proper partition constraint ∑u_ik=1
# and non-trivial solution via auxiliary regularization.
# ============================================================

class Type2FuzzyConstraintModule:
    """
    Type-2 Fuzzy Clustering with symbolic constraint injection.

    Fixes over previous version:
    1. Partition constraint ∑_i u_ik = 1 enforced (avoids trivial u=0 solution)
    2. Uncertainty width δ is data-adaptive, not fixed
    3. Memberships weighted by cluster reliability
    4. Constraint violation is quantifiable and differentiable
    """

    def __init__(self, n_clusters=3, m=2.0, delta=0.1, max_iter=150, eps=1e-4):
        self.c = n_clusters
        self.m = m          # fuzziness exponent
        self.delta = delta  # base uncertainty half-width
        self.max_iter = max_iter
        self.eps = eps
        self.centers = None
        self.U_lower = None
        self.U_upper = None
        self.convergence_history = []

    def fit(self, Z):
        """
        Fit Type-2 Fuzzy C-Means on latent representation Z.
        Returns lower/upper memberships and cluster centers.
        Z: (n_samples, latent_dim) numpy array
        """
        n, d = Z.shape
        # Initialize membership matrix with partition constraint
        U = np.random.dirichlet(np.ones(self.c), size=n).T  # (c, n)
        # Ensure partition: each column sums to 1
        U = U / U.sum(axis=0, keepdims=True)

        prev_J = np.inf
        self.convergence_history = []

        for iteration in range(self.max_iter):
            # Step 1: Update cluster centers
            um = U ** self.m  # (c, n)
            centers = (um @ Z) / (um.sum(axis=1, keepdims=True) + 1e-10)  # (c, d)

            # Step 2: Update memberships (standard fuzzy c-means update)
            dist = np.zeros((self.c, n))
            for i in range(self.c):
                diff = Z - centers[i]  # (n, d)
                dist[i] = np.sqrt((diff ** 2).sum(axis=1) + 1e-10)

            # Standard FCM update with partition constraint guaranteed
            tmp = (dist + 1e-10) ** (-2.0 / (self.m - 1))
            U_new = tmp / tmp.sum(axis=0, keepdims=True)  # partition enforced

            # Step 3: Compute objective (with partition constraint, no trivial solution)
            J = float(((U_new ** self.m) * (dist ** 2)).sum())
            self.convergence_history.append(J)

            # Step 4: Apply Type-2 bounds (data-adaptive δ)
            # Width reflects local data density — denser regions get narrower bounds
            density = np.exp(-dist.mean(axis=1, keepdims=True) / dist.mean())
            delta_adaptive = self.delta / (density + 1e-5)  # (c, n)

            U_lower = np.clip(U_new - delta_adaptive, 0, 1)
            U_upper = np.clip(U_new + delta_adaptive, 0, 1)

            # Re-enforce approximate partition on lower bounds
            row_sum_lower = U_lower.sum(axis=0, keepdims=True)
            U_lower = U_lower / np.maximum(row_sum_lower, 1.0)

            # Check convergence
            if abs(prev_J - J) < self.eps:
                print(f"  Fuzzy converged at iteration {iteration+1}, J={J:.6f}")
                break
            prev_J = J
            U = U_new

        self.centers = centers
        self.U_lower = U_lower
        self.U_upper = U_upper
        return centers, U_lower, U_upper

    def compute_constraint_loss_numpy(self, Z):
        """
        Computes how much the current latent representation Z
        violates the symbolic fuzzy constraints. Used for monitoring.
        Returns scalar loss value.
        """
        if self.centers is None:
            return 0.0
        n, d = Z.shape
        dist = np.array([
            np.sqrt(((Z - self.centers[i]) ** 2).sum(axis=1) + 1e-10)
            for i in range(self.c)
        ])  # (c, n)
        # Violation: memberships that fall outside [U_lower, U_upper]
        tmp = (dist + 1e-10) ** (-2.0 / (self.m - 1))
        U_current = tmp / (tmp.sum(axis=0, keepdims=True) + 1e-10)
        violation_lower = np.maximum(self.U_lower - U_current, 0)
        violation_upper = np.maximum(U_current - self.U_upper, 0)
        return float((violation_lower ** 2 + violation_upper ** 2).mean())

    def get_avg_memberships(self):
        """Returns average (lower+upper)/2 memberships"""
        return (self.U_lower + self.U_upper) / 2.0


