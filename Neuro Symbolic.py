class NeuralEncoder(nn.Module):
    """
    Maps high-dimensional input to a symbolic latent space.
    Architecture: input_dim → 64 → 32 → latent_dim
    The latent space is where symbolic (fuzzy) constraints are applied.
    """
    def __init__(self, input_dim, latent_dim=8):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, 64),
            nn.BatchNorm1d(64),
            nn.ReLU(),
            nn.Dropout(0.1),
            nn.Linear(64, 32),
            nn.BatchNorm1d(32),
            nn.ReLU(),
            nn.Linear(32, latent_dim)
        )

    def forward(self, x):
        return self.net(x)


class NeuralDecoder(nn.Module):
    """
    Reconstructs input from latent representation.
    Architecture: latent_dim → 32 → 64 → input_dim
    """
    def __init__(self, latent_dim=8, output_dim=10):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(latent_dim, 32),
            nn.BatchNorm1d(32),
            nn.ReLU(),
            nn.Linear(32, 64),
            nn.BatchNorm1d(64),
            nn.ReLU(),
            nn.Linear(64, output_dim)
        )

    def forward(self, z):
        return self.net(z)


