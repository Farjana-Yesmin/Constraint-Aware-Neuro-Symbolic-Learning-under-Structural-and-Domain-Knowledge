# CELL 6 — Differentiable Constraint Loss (bridges symbolic→neural)
# This is the KEY contribution for genuine neuro-symbolic integration.
# The symbolic fuzzy constraints produce a differentiable loss that
# backpropagates through the neural encoder.
# ============================================================

def compute_fuzzy_clustering_loss(Z_tensor, centers_tensor, m=2.0):
    """
    Differentiable fuzzy c-means loss in PyTorch.
    Symbolic → Neural: gradients flow from this loss to the encoder.

    Z_tensor: (n, latent_dim) torch tensor — neural output
    centers_tensor: (c, latent_dim) torch tensor — symbolic cluster centers
    m: fuzziness parameter

    Returns: scalar loss, membership matrix (n, c)
    """
    n = Z_tensor.shape[0]
    c = centers_tensor.shape[0]

    # Pairwise distances (n, c)
    dist = torch.cdist(Z_tensor, centers_tensor, p=2) + 1e-8  # (n, c)

    # Fuzzy membership update — partition constraint via softmin
    exponent = -2.0 / (m - 1)
    tmp = dist ** exponent  # (n, c)
    U = tmp / tmp.sum(dim=1, keepdim=True)  # (n, c) — partition enforced

    # Fuzzy c-means objective
    J = (U ** m * dist ** 2).sum()

    # Auxiliary regularization: penalize uniform memberships
    # (prevents near-trivial solutions where all U ≈ 1/c)
    entropy_reg = -(U * (U + 1e-8).log()).sum(dim=1).mean()
    # We MINIMIZE J and MAXIMIZE cluster confidence (penalize high entropy)
    loss = J / n + 0.01 * entropy_reg  # entropy_reg is positive, so this penalizes ambiguity

    return loss, U


def compute_constraint_violation_loss(U, U_lower_tensor, U_upper_tensor):
    """
    Penalizes neural representations that violate symbolic constraints.
    Symbolic bounds [U_lower, U_upper] define valid membership regions.
    Neural encoder is penalized for producing latent vectors outside them.

    This is the SYMBOLIC→NEURAL direction of bidirectional integration.
    U: (n, c) current memberships from encoder output
    U_lower_tensor, U_upper_tensor: (c, n) symbolic constraint bounds
    """
    U_lower_T = U_lower_tensor.T  # (n, c)
    U_upper_T = U_upper_tensor.T  # (n, c)
    viol_lower = torch.clamp(U_lower_T - U, min=0.0)
    viol_upper = torch.clamp(U - U_upper_T, min=0.0)
    return (viol_lower ** 2 + viol_upper ** 2).mean()


